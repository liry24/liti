import type { LitiConfig } from './config'
import { createLitiDescriptor } from './descriptor'

export const generateLitiTypes = (
    configImport: string,
    environments: readonly string[],
): string => `// Generated by liti generate. Do not edit.
import type { InferLitiSchema, ResolvedLitiConfig, InferLitiMeta } from 'liti'
import 'liti/client'
type Config = ResolvedLitiConfig<typeof import(${JSON.stringify(configImport)}).default, readonly ${JSON.stringify(environments)}>
export type Schema = InferLitiSchema<Config>
declare module 'liti/client' {
    interface LitiClientRegistry extends Schema {
        modelMeta: InferLitiMeta<Config>
    }
}
`

export const generateLitiDescriptor = (config: LitiConfig): string =>
    JSON.stringify(createLitiDescriptor(config), null, 2) + '\n'
